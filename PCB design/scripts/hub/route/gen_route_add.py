def _inside(px, py, net, layer, segs, vias, pads, skip):
    """True when (px, py) lies in other same-net copper: a track of that layer (not `skip`), a via or a pad."""
    from shapely.geometry import Point, Polygon
    for k, q in enumerate(segs):
        if k != skip and q[0] == layer:
            dx, dy = q[3] - q[1], q[4] - q[2]
            L2 = dx * dx + dy * dy
            t = 0 if L2 == 0 else max(0.0, min(1.0, ((px - q[1]) * dx + (py - q[2]) * dy) / L2))
            if math.hypot(px - q[1] - t * dx, py - q[2] - t * dy) < q[5] / 2 - 0.5:
                return True
    if any(math.hypot(px - v[0], py - v[1]) < v[3] / 2 - 0.5 for v in vias):
        return True
    return any(p.net == net and layer in p.layers and Polygon(p.poly).buffer(-0.5).contains(Point(px, py)) for p in pads)


def main():
    import route_model as M
    pads, _, _ = M.build()
    routes = json.load(open(os.path.join(HERE, 'data', 'routes.json'), encoding='utf-8'))
    V, S = [], []
    dropped = 0
    for net, r in sorted(routes.items()):
        for v in r['vias']:
            V.append([net, round(v[0] - LP.OX, 2), round(v[1] - LP.OY, 2), round(v[2], 3), round(v[3], 3)])
        for k, s in enumerate(r['segs']):
            # a stub no longer than its width with both ends already in same-net copper: EasyEDA drops it on create
            # (playbook §7), so writing it would only make every re-run "create" it again
            if math.hypot(s[3] - s[1], s[4] - s[2]) <= s[5] and                     _inside(s[1], s[2], net, s[0], r['segs'], r['vias'], pads, k) and                     _inside(s[3], s[4], net, s[0], r['segs'], r['vias'], pads, k):
                dropped += 1
                continue
            S.append([net, 1 if s[0] == 0 else 2, round(s[1] - LP.OX, 2), round(s[2] - LP.OY, 2),
                      round(s[3] - LP.OX, 2), round(s[4] - LP.OY, 2), round(s[5], 3)])
    js = JS.replace('/*VIAS*/', json.dumps(V)).replace('/*SEGS*/', json.dumps(S))
    open(os.path.join(HERE, '40_route_add.js'), 'w', encoding='utf-8').write(js)
    print('wrote 40_route_add.js: %d vias, %d segments, %d nets (%d covered stubs skipped)' % (len(V), len(S), len(routes), dropped))


if __name__ == '__main__':
    main()
