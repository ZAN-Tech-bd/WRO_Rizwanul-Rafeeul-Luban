# Station board v0.4 PCB (from the pcb-pipeline template): generates 40_route.js (tracks + vias from data/routes.json,
# written by route_plan.py). No 41_pour.js: API pours never fill; the GND copper is pour_fill.py -> 42_fill.js.
# Usage: python gen_route_js.py   [test: --routes=data/x.json --nets=ANT1 --out=<scratch>/40_test.js]
import json
import os


HERE = os.path.dirname(os.path.abspath(__file__))
ORDER_FIRST = ['GND']  # GND last actually: see sort below

ROUTE_JS = r"""// GENERATED by gen_route_js.py from data/routes.json (route_plan.py). Do not edit.
// Station board v0.4 PCB — tracks (layers 1 top / 2 bottom) and vias, per net.
// Idempotent per net: a net whose existing tracks + vias already match the plan geometrically is skipped; otherwise its
// tracks/vias are deleted and re-created. EasyEDA tidies tracks on creation (merges consecutive collinear segments of
// one width, drops segments shorter than their width that sit inside neighbouring copper; 2026-10-15), so "match" =
// every existing track lies on the planned path (same layer + width, within 0.6 mil), every planned segment longer
// than its width is covered by an existing track, and the vias match exactly.
// Time-boxed (~16 s of writing): re-run until "remaining": [].
// Run: node "D:\projects\WRO_Rizwanul-Rafeeul-Luban\tools\easyeda-bridge\eda.mjs" exec -f "D:\projects\WRO_Rizwanul-Rafeeul-Luban\PCB design\scripts\station\40_route.js"
const PROJECT = 'station_pcb';
if (document.visibilityState !== 'visible') return JSON.stringify({ abort: 'EasyEDA window is hidden: bring it to the front' });
const proj = await eda.dmt_Project.getCurrentProjectInfo();
if (!proj || (proj.friendlyName || proj.name) !== PROJECT) return JSON.stringify({ abort: 'open project is not ' + PROJECT });
const tree = await eda.dmt_EditorControl.getSplitScreenTree();
const tab = ((tree && tree.tabs) || []).find((t) => /pcb/i.test(t.title));
if (!tab) return JSON.stringify({ abort: 'no PCB tab' });
await eda.dmt_EditorControl.activateDocument(tab.tabId);
{ const _t = Date.now(); while (Date.now() - _t < 500) await eda.dmt_Project.getCurrentProjectInfo(); } // no timers (hidden window)
const R = /*ROUTES*/;
const t0 = Date.now();
const res = { done: [], skipped: [], remaining: [], created: 0, deleted: 0, errors: [] };
const allLines = ((await eda.pcb_PrimitiveLine.getAll()) || []).filter((l) => ['1', '2'].includes(String(l.getState_Layer())));
const allVias = (await eda.pcb_PrimitiveVia.getAll()) || [];
const byNetL = {}, byNetV = {};
for (const l of allLines) (byNetL[l.getState_Net()] = byNetL[l.getState_Net()] || []).push(l);
for (const v of allVias) (byNetV[v.getState_Net()] = byNetV[v.getState_Net()] || []).push(v);
const near = (a, b) => Math.abs(a - b) < 0.6;
const dPtSeg = (px, py, s) => {   // s = [layer, x1, y1, x2, y2, width]
  const dx = s[3] - s[1], dy = s[4] - s[2], L2 = dx * dx + dy * dy;
  const t = L2 === 0 ? 0 : Math.max(0, Math.min(1, ((px - s[1]) * dx + (py - s[2]) * dy) / L2));
  return Math.hypot(px - s[1] - t * dx, py - s[2] - t * dy);
};
const onAny = (px, py, lay, w, segs) => segs.some((s) => s[0] === lay && near(s[5], w) && dPtSeg(px, py, s) < 0.6);
function sameSegs(plan, el) {
  if (!el.length) return plan.length === 0;
  const ex = el.map((l) => [Number(l.getState_Layer()), l.getState_StartX(), l.getState_StartY(), l.getState_EndX(), l.getState_EndY(), l.getState_LineWidth()]);
  const pl = plan.map(([L, x1, y1, x2, y2, w]) => [L === 0 ? 1 : 2, x1, y1, x2, y2, w]);
  for (const e of ex) for (const f of [0, 0.25, 0.5, 0.75, 1])
    if (!onAny(e[1] + f * (e[3] - e[1]), e[2] + f * (e[4] - e[2]), e[0], e[5], pl)) return false;
  for (const p of pl) {
    if (Math.hypot(p[3] - p[1], p[4] - p[2]) <= p[5]) continue;   // EasyEDA may drop it (inside neighbouring copper)
    for (const f of [0.25, 0.5, 0.75])
      if (!onAny(p[1] + f * (p[3] - p[1]), p[2] + f * (p[4] - p[2]), p[0], p[5], ex)) return false;
  }
  return true;
}
function sameVias(plan, ev) {
  if (plan.length !== ev.length) return false;
  const ex = ev.map((v) => [v.getState_X(), v.getState_Y(), v.getState_HoleDiameter(), v.getState_Diameter()]);
  const used = new Array(ex.length).fill(false);
  for (const [x, y, d, D] of plan) {
    // EasyEDA rounds via hole / diameter to whole mils (0.5/1.0 mm = 19.68/39.37 -> 20/40): 1 mil on the sizes
    const k = ex.findIndex((e, i) => !used[i] && near(e[0], x) && near(e[1], y) && Math.abs(e[2] - d) < 1 && Math.abs(e[3] - D) < 1);
    if (k < 0) return false;
    used[k] = true;
  }
  return true;
}
const FORCE = new Set(/*FORCE*/);   // nets to delete + re-create even when they match (gen_route_js.py --force=)
for (const [net, [segs, vias]] of R) {
  const el = byNetL[net] || [], ev = byNetV[net] || [];
  if (!FORCE.has(net) && sameSegs(segs, el) && sameVias(vias, ev)) { res.skipped.push(net); continue; }
  // time box: ~25 ms per create; don't start a net that would run past ~16 s (GND alone is ~350 creates) unless it
  // is the first one this run (progress guaranteed)
  const busy = res.done.length > 0;
  if (Date.now() - t0 > 16000 || (busy && Date.now() - t0 + 30 * (segs.length + vias.length) > 18000)) { res.remaining.push(net); continue; }
  if (el.length) { await eda.pcb_PrimitiveLine.delete(el.map((l) => l.getState_PrimitiveId())); res.deleted += el.length; }
  if (ev.length) { await eda.pcb_PrimitiveVia.delete(ev.map((v) => v.getState_PrimitiveId())); res.deleted += ev.length; }
  let ok = true;
  // vias FIRST: a track links to the vias / pads / tracks already at its ends when it is created, but a via created
  // later is not linked to existing tracks (DRC "track is disconnected" on both tracks at every via, 2026-10-15)
  for (const [x, y, drill, dia] of vias) {
    try { await eda.pcb_PrimitiveVia.create(net, x, y, drill, dia); res.created++; }
    catch (e) { res.errors.push(net + ' via ' + e); ok = false; break; }
  }
  for (const [layer, x1, y1, x2, y2, w] of (ok ? segs : [])) {
    try { await eda.pcb_PrimitiveLine.create(net, layer === 0 ? 1 : 2, x1, y1, x2, y2, w); res.created++; }
    catch (e) { res.errors.push(net + ' seg ' + e); ok = false; break; }
  }
  if (ok) res.done.push(net);
}
await eda.pcb_Document.save();
res.ms = Date.now() - t0;
return JSON.stringify(res);
"""

def main():
    import sys
    src = next((a.split('=', 1)[1] for a in sys.argv if a.startswith('--routes=')), os.path.join(HERE, 'data', 'routes.json'))
    only = next((a.split('=', 1)[1].split(',') for a in sys.argv if a.startswith('--nets=')), None)
    out = next((a.split('=', 1)[1] for a in sys.argv if a.startswith('--out=')), os.path.join(HERE, '40_route.js'))
    routes = json.load(open(src, encoding='utf-8'))
    if only:  # test mode: a subset of nets into a separate script, no pour script
        routes = {n: routes[n] for n in only}
    order = sorted([n for n in routes if n != 'GND']) + (['GND'] if 'GND' in routes else [])
    data = [[n, [routes[n]['segs'], routes[n]['vias']]] for n in order]
    # --force=NET,NET (or --force=@vias = every net with vias): delete + re-create them even when they match
    force = next((a.split('=', 1)[1] for a in sys.argv if a.startswith('--force=')), '')
    force = [n for n in order if routes[n]['vias']] if force == '@vias' else [n for n in force.split(',') if n]
    js = ROUTE_JS.replace('/*ROUTES*/', json.dumps(data, separators=(',', ':'))).replace('/*FORCE*/', json.dumps(force))
    open(out, 'w', encoding='utf-8').write(js)
    if only:
        print('wrote %s (%s)' % (out, ', '.join(order)))
        return
    nseg = sum(len(routes[n]['segs']) for n in routes)
    nvia = sum(len(routes[n]['vias']) for n in routes)
    print('wrote 40_route.js (%d nets, %d segments, %d vias)' % (len(order), nseg, nvia))


if __name__ == '__main__':
    main()
